/**
 * Markdown 语法检测：
 * 供「粘贴识别」（markdown-paste-handler）与「存量原文 Markdown 兜底转换」
 * （raw-markdown）共用，保证两处判定口径一致。
 *
 * 匹配特征包括：
 * - 标题 / 引用 / 水平线
 * - 有序 / 无序列表、任务列表、围栏代码块
 * - GFM 表格、脚注、数学公式（$ / $$）
 * - 图片 / 链接、行内代码
 * - 加粗、斜体、删除线、高亮
 */
export const MARKDOWN_SYNTAX_PATTERN =
  /(?:^|\n)\s{0,3}#{1,6}\s|(?:^|\n)\s{0,3}(?:[-*+]\s|\d+\.\s)|(?:^|\n)\s{0,3}>(?:\s|$)|(?:^|\n)\s{0,3}(?:-{3,}|\*{3,}|_{3,})\s*(?=\n|$)|```|~~~|\$\$|\$(?!\s)[^$\n]+?\$|\[\^[^\]\s]+\]|\|\s*[^|\n]+\s*\||!\[[^\]]*\]\([^)]*\)|\[[^\]\n]+\]\([^)\n]+\)|\*\*[^*\n]+\*\*|~~[^~\n]+~~|==[^=\n]+==|(?:^|[\s(（[*_`])[*_][^\s*_\n][^*_\n]*[*_](?=[\s)\]）"'，。！？；：、,.;:!?]|$)|(?:^|[\s(（`])`[^`\n]+`(?:[\s.,;:!?，。；：！？、]|$)/;

/** 判断给定文本是否包含 Markdown 语法特征 */
export function hasMarkdownSyntax(text: string): boolean {
  return MARKDOWN_SYNTAX_PATTERN.test(text);
}
